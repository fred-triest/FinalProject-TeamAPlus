    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        
        // Get selected org
        String selectedOrgName = (String) cmbOrganization.getSelectedItem();
        Organization selectedOrg = null;
        for (Organization org : enterprise.getOrganizationDirectory().getOrganizationList()) {
            if (org.getName().equals(selectedOrgName)) {
                selectedOrg = org;
                break;
            }
        }
        
        if (selectedOrg == null) {
            JOptionPane.showMessageDialog(null, "You must select a valid organization", "Validation Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        
        // Get selected role
        String selectedRoleName = (String) cmbRole.getSelectedItem();
        Role selectedRole = null;
        for (Role role : selectedOrg.getSupportedRole()) {
            if (role.toString().equals(selectedRoleName)) {
                selectedRole = role;
                break;
            }
        }
        
        if (selectedRole == null) {
            JOptionPane.showMessageDialog(null, "You must select a valid role", "Validation Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        
        // Confirm fields are valid
        String name = txtName.getText().trim();
        String email = txtEmail.getText().trim();
        String phone = txtPhone.getText().trim();
        String title = txtTitle.getText().trim();
        String username = txtUsername.getText().trim();
        String password = txtPassword.getText().trim();
        String ageText = txtAge.getText().trim();
        
        if (name.isEmpty() || email.isEmpty() || phone.isEmpty() || title.isEmpty()|| username.isEmpty() || password.isEmpty() || ageText.isEmpty()) {
            JOptionPane.showMessageDialog(null, "You must fill in all of the fields", "Validation Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        
        int age;
        try {
            age = Integer.parseInt(ageText);
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(null, "Age can only be a number", "Validation Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        
        if (!selectedOrg.getUserAccountDirectory().checkIfUsernameIsUnique(username)) {
            JOptionPane.showMessageDialog(null, "The username already exists", "Validation Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        
        // Create user account and employee in the selected org
        Employee employee = selectedOrg.getEmployeeDirectory().createEmployee(name, email, phone, title, age);
        selectedOrg.getUserAccountDirectory().createUserAccount(username, password, employee, selectedRole);
        
        populateTable();
        clearFields();
        JOptionPane.showMessageDialog(null, "User successfully created", "Success", JOptionPane.INFORMATION_MESSAGE);
    
    }//GEN-LAST:event_btnAddActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        
        int selectedRow = tblUsers.getSelectedRow();
        if (selectedRow < 0) {
            JOptionPane.showMessageDialog(null, "You must select a user to update", "Validation Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        
        String name = txtName.getText().trim();
        String email = txtEmail.getText().trim();
        String phone = txtPhone.getText().trim();
        String title = txtTitle.getText().trim();
        String ageText = txtAge.getText().trim();
        
        if (name.isEmpty() && email.isEmpty() && phone.isEmpty() && title.isEmpty() && ageText.isEmpty()) {
            JOptionPane.showMessageDialog(null, "You must enter at least one field to update", "Validation Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        
        String accountId = (String) tblUsers.getValueAt(selectedRow, 0);
        
        // Search the enterprise then orgs for matching the account
        for (UserAccount ua : enterprise.getUserAccountDirectory().getUserAccountList()) {
            if (ua.getUserAccountId().equals(accountId)) {
                updateEmployee(ua, name, email, phone, title, ageText);
                return;
            }
        }
        
        for (Organization org : enterprise.getOrganizationDirectory().getOrganizationList()) {
            for (UserAccount ua : org.getUserAccountDirectory().getUserAccountList()) {
                if (ua.getUserAccountId().equals(accountId)) {
                    updateEmployee(ua, name, email, phone, title, ageText);
                    return;
                }
            }
        }
    }
    
    // Extracted update logic to avoid repeating it in two places
    private void updateEmployee(UserAccount ua, String name, String email, String phone, String title, String ageText) {
        if (!name.isEmpty()) ua.getEmployee().setName(name);
        if (!email.isEmpty()) ua.getEmployee().setEmail(email);
        if (!phone.isEmpty()) ua.getEmployee().setPhone(phone);
        if (!title.isEmpty()) ua.getEmployee().setTitle(title);
        if (!ageText.isEmpty()) {
            try {
                ua.getEmployee().setAge(Integer.parseInt(ageText));
            } catch (NumberFormatException e) {
                JOptionPane.showMessageDialog(null, "The age must be a number", "Validation Error", JOptionPane.ERROR_MESSAGE);
                return;
            }
        }
        
        populateTable();
        clearFields();
        JOptionPane.showMessageDialog(null, "The user has been successfully updated", "Success", JOptionPane.INFORMATION_MESSAGE);
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        
        int selectedRow = tblUsers.getSelectedRow();
        if (selectedRow < 0) {
            JOptionPane.showMessageDialog(null, "You must select a user to delete", "Validation Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        
        int confirm = JOptionPane.showConfirmDialog(null, "Are you sure you want to delete this user?", "Confirm Delete", JOptionPane.YES_NO_OPTION);
        if (confirm != JOptionPane.YES_OPTION)
            return;
        
        
        String accountId = (String) tblUsers.getValueAt(selectedRow, 0);
        
        // Search enterprise first
        for (UserAccount ua : enterprise.getUserAccountDirectory().getUserAccountList()) {
            if (ua.getUserAccountId().equals(accountId)) {
                enterprise.getUserAccountDirectory().getUserAccountList().remove(ua);
                populateTable();
                JOptionPane.showMessageDialog(null, "You have successfully deletedd this user", "Success", JOptionPane.INFORMATION_MESSAGE);
                return;
            }
        }
        
        // Search org level next
        for (Organization org : enterprise.getOrganizationDirectory().getOrganizationList()) {
            for (UserAccount ua : org.getUserAccountDirectory().getUserAccountList()) {
                if (ua.getUserAccountId().equals(accountId)) {
                    org.getUserAccountDirectory().getUserAccountList().remove(ua);
                    populateTable();
                    JOptionPane.showMessageDialog(null, "You have successfully delete this user", "Success", JOptionPane.INFORMATION_MESSAGE);
                    return;
                }
            }
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

