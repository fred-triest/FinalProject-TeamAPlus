    // Populates organization picklist with the enterprise's organizations
    public void populateOrganizationComboBox() {
        cmbOrganization.removeAllItems();
        for (Organization org : enterprise.getOrganizationDirectory().getOrganizationList()) {
            cmbOrganization.addItem(org.getName());
        }
    }
    
    // Populates role picklist based on the selected organization's supported roles
    public void populateRoleComboBox() {
        cmbRole.removeAllItems();
        String selectedOrgName = (String) cmbOrganization.getSelectedItem();
        for (Organization org : enterprise.getOrganizationDirectory().getOrganizationList()) {
            if (org.getName().equals(selectedOrgName)) {
                for (Role role : org.getSupportedRole()) {
                    cmbRole.addItem(role.toString());
                }
                break;
            }
        }
    }
    
    // Display all users in the enterprise and all orgs
    public void populateTable() {
        DefaultTableModel model = (DefaultTableModel) tblUsers.getModel();
        model.setRowCount(0);
        
        // Enterprise users
        for (UserAccount ua : enterprise.getUserAccountDirectory().getUserAccountList()) {
            Object[] row = {ua.getUserAccountId(), ua.getEmployee().getName(),ua.getUsername(), ua.getRole().toString(), "Enterprise Level"};
            model.addRow(row);
        }
        
        // Organization users
        for (Organization org : enterprise.getOrganizationDirectory().getOrganizationList()) {
            for (UserAccount ua : org.getUserAccountDirectory().getUserAccountList()) {
                Object[] row = {ua.getUserAccountId(), ua.getEmployee().getName(), ua.getUsername(), ua.getRole().toString(), org.getName()};
                model.addRow(row);
            }
        }
    }
    
